// The headers of each style, as a file starts with them.
const (
	slashHeader = "// SPDX-License-Identifier: Apache-2.0\n// SPDX-FileCopyrightText: The Pumi Authors\n"
	hashHeader  = "# SPDX-License-Identifier: Apache-2.0\n# SPDX-FileCopyrightText: The Pumi Authors\n"
	htmlHeader  = "<!--\nSPDX-License-Identifier: Apache-2.0\nSPDX-FileCopyrightText: The Pumi Authors\n-->\n"
)

// TestClassify lists every rule of the check: which files are source, in
// which comment syntax, and which are exempt.
func TestClassify(t *testing.T) {
	tests := []struct {
		path string
		want Style
	}{
		{"main.go", Slash},
		{"internal/shared/version_test.go", Slash},
		{"internal/checks/lintconfig/testdata/todo/todo.go", Slash},
		{"go.mod", Slash},
		{"api/go.mod", Slash},
		{"tools/buf.mod", Slash},
		{".devcontainer/devcontainer.json", Slash},
		{"Makefile", Hash},
		{".devcontainer/Dockerfile", Hash},
		{".gitignore", Hash},
		{"api/.gitignore", Hash},
		{".golangci.yml", Hash},
		{".github/workflows/ci.yml", Hash},
		{".github/dependabot.yaml", Hash},
		{".devcontainer/install-tools.sh", Hash},
		{"README.md", HTML},
		{"AGENTS.md", HTML},
		{"internal/kernel/README.md", HTML},
		{"LICENSE", Exempt},
		{"NOTICE", Exempt},
		{"CLAUDE.md", Exempt},
		{"go.sum", Exempt},
		{"api/go.sum", Exempt},
		{"tools/buf.sum", Exempt},
		{".pumi/agent-identities.json", Exempt},
		{"api/schemas/event.json", Exempt},
		{"internal/CLAUDE.md", HTML},
		{"docs/LICENSE", Unknown},
		{"logo.png", Unknown},
		{"script.py", Unknown},
		{"Makefile.old", Unknown},
		{"devcontainer.json", Exempt},
	}
	for _, tt := range tests {
		if got := Classify(tt.path); got != tt.want {
			t.Errorf("Classify(%q) = %v, want %v", tt.path, got, tt.want)
		}
	}
}

func file(src string) *fstest.MapFile {
	return &fstest.MapFile{Data: []byte(src)}
}

func TestCheckPassesFilesWithHeaders(t *testing.T) {
	fsys := fstest.MapFS{
		"main.go":                         file(slashHeader + "\npackage main\n"),
		"go.mod":                          file(slashHeader + "\nmodule example.com/m\n"),
		".devcontainer/devcontainer.json": file(slashHeader + "{}\n"),
		"Makefile":                        file(hashHeader + "\nbuild:\n"),
		"ci.yml":                          file(hashHeader + "\nname: CI\n"),
		"install.sh":                      file("#!/bin/sh\n" + hashHeader + "\nset -eu\n"),
		"README.md":                       file(htmlHeader + "\n# Title\n"),
		"LICENSE":                         file("Apache License\n"),
		"NOTICE":                          file("Pumi\n"),
		"CLAUDE.md":                       file("@AGENTS.md\n"),
		"go.sum":                          file("example.com/m v1.0.0 h1:x=\n"),
		".pumi/agent-identities.json":     file("{}\n"),
		"gen.pb.go":                       file("// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage gen\n"),
		"gen2.go":                         file("// Copyright notice of the generator.\n\n// Code generated by stringer; DO NOT EDIT.\n\npackage gen\n"),
	}
	var paths []string
	for p := range fsys {
		paths = append(paths, p)
	}
	findings, err := Check(fsys, paths)
	if err != nil {
		t.Fatalf("Check() error = %v", err)
	}
	if len(findings) != 0 {
		t.Errorf("Check() = %v, want no findings", findings)
	}
}

func TestCheckFailsFilesWithoutHeaders(t *testing.T) {
	tests := []struct {
		name string
		path string
		src  string
		want string
	}{
		{"no header", "p.go", "package p\n", missingSlash},
		{"empty file", "p.go", "", missingSlash},
		{"one line only", "p.go", "// SPDX-License-Identifier: Apache-2.0\n\npackage p\n", missingSlash},
		{"lines in the wrong order", "p.go", "// SPDX-FileCopyrightText: The Pumi Authors\n// SPDX-License-Identifier: Apache-2.0\n", missingSlash},
		{"another license", "p.go", "// SPDX-License-Identifier: MIT\n// SPDX-FileCopyrightText: The Pumi Authors\n", missingSlash},
		{"another holder", "p.go", "// SPDX-License-Identifier: Apache-2.0\n// SPDX-FileCopyrightText: Someone Else\n", missingSlash},
		{"header after other text", "p.go", "// Package p.\n" + slashHeader, missingSlash},
		{"header after a blank line", "p.go", "\n" + slashHeader, missingSlash},
		{"header without a final newline", "p.go", slashHeader[:len(slashHeader)-1], missingSlash},
		{"carriage returns", "p.go", "// SPDX-License-Identifier: Apache-2.0\r\n// SPDX-FileCopyrightText: The Pumi Authors\r\n", missingSlash},
		{"byte order mark", "p.go", "\ufeff" + slashHeader, missingSlash},
		{"wrong comment syntax", "p.go", hashHeader, missingSlash},
		{"generated marker after code", "p.go", "package p\n\n// Code generated by x. DO NOT EDIT.\n", missingSlash},
		{"generated marker without DO NOT EDIT", "p.go", "// Code generated by x.\n\npackage p\n", missingSlash},
		{"yaml without header", "ci.yml", "name: CI\n", missingHash},
		{"shell without header", "x.sh", "#!/bin/sh\nset -eu\n", missingHash},
		{"shebang in a Makefile", "Makefile", "#!/usr/bin/make -f\n" + hashHeader, missingHash},
		{"markdown with slash comments", "README.md", slashHeader, missingHTML},
		{"markdown with the comment on one line", "README.md", "<!-- SPDX-License-Identifier: Apache-2.0 SPDX-FileCopyrightText: The Pumi Authors -->\n", missingHTML},
		{"generated marker in yaml", "ci.yml", "# Code generated by x. DO NOT EDIT.\nname: CI\n", missingHash},
		{"unknown file type", "logo.png", "\x89PNG", unknown},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := Check(fstest.MapFS{tt.path: file(tt.src)}, []string{tt.path})
			if err != nil {
				t.Fatalf("Check() error = %v", err)
			}
			want := []Finding{{Path: tt.path, Problem: tt.want}}
			if !reflect.DeepEqual(got, want) {
				t.Errorf("Check() = %+v, want %+v", got, want)
			}
		})
	}
}

const (
	missingSlash = "does not start with the two SPDX lines as // comments (decision 0068)"
	missingHash  = "does not start with the two SPDX lines as # comments (decision 0068)"
	missingHTML  = "does not start with the two SPDX lines in an HTML comment (decision 0068)"
	unknown      = "has a file type that the SPDX check does not list; list it in internal/checks/spdx as a source type or as exempt (decision 0068)"
)

func TestCheckFailsCLAUDEmdWithMoreThanTheImport(t *testing.T) {
	for _, src := range []string{"@AGENTS.md\nMore instructions.\n", htmlHeader + "@AGENTS.md\n", "@AGENTS.md", ""} {
		got, err := Check(fstest.MapFS{"CLAUDE.md": file(src)}, []string{"CLAUDE.md"})
		if err != nil {
			t.Fatalf("Check() error = %v", err)
		}
		want := []Finding{{Path: "CLAUDE.md", Problem: "is exempt only while it holds only the line @AGENTS.md (decisions 0068 and 0091)"}}
		if !reflect.DeepEqual(got, want) {
			t.Errorf("Check() of %q = %+v, want %+v", src, got, want)
		}
	}
}

func TestCheckReportsInTheOrderGiven(t *testing.T) {
	fsys := fstest.MapFS{"b.go": file(""), "a.go": file("")}
	got, err := Check(fsys, []string{"b.go", "a.go"})
	if err != nil {
		t.Fatalf("Check() error = %v", err)
	}
	want := []Finding{{Path: "b.go", Problem: missingSlash}, {Path: "a.go", Problem: missingSlash}}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("Check() = %+v, want %+v", got, want)
	}
}

func TestCheckSkipsMissingFilesAndDirectories(t *testing.T) {
	fsys := fstest.MapFS{"sub/p.go": file(slashHeader)}
	got, err := Check(fsys, []string{"gone.go", "sub"})
	if err != nil {
		t.Fatalf("Check() error = %v", err)
	}
	if len(got) != 0 {
		t.Errorf("Check() = %+v, want no findings", got)
	}
}

func TestCheckSkipsSymbolicLinks(t *testing.T) {
	fsys := fstest.MapFS{"link.go": &fstest.MapFile{Data: []byte("target.go"), Mode: fs.ModeSymlink}}
	got, err := Check(fsys, []string{"link.go"})
	if err != nil || len(got) != 0 {
		t.Errorf("Check() = %+v, %v; want no findings and no error", got, err)
	}
}

func TestFindingString(t *testing.T) {
	f := Finding{Path: "a/p.go", Problem: missingSlash}
	if got, want := f.String(), "a/p.go: "+missingSlash; got != want {
		t.Errorf("String() = %q, want %q", got, want)
	}
}
